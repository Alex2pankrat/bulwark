#!/usr/bin/env python3
"""Generates Godot .po translation files from the source-string table in src/core/l10n.gd.

Design
------
The English source strings live in `l10n.gd` as the `EN` table (key -> English). The English
value of each key is the .po `msgid`. Translations live **only** in the `.po` files — this is the
file a community translator edits with any i18n tool, never the GDScript.

The generator is therefore two-directional:
  * It reads the current `EN` table (source of truth for keys and source strings).
  * It reads any existing `.po` files and **preserves** their `msgstr` for strings that still
    exist, so re-running it after adding/renaming a source string never wipes a translator's work.
  * Newly added source strings get an empty `msgstr` (the loader falls back to English until
    someone translates them).

Run after editing the EN table in l10n.gd:
    python3 tools/gen_locales.py

Output:
    assets/locales/en.po   (msgid == msgstr, the source language)
    assets/locales/ru.po   (Russian msgstr, preserved across runs)
"""

import ast
import re
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
L10N = ROOT / "src" / "core" / "l10n.gd"
OUT_DIR = ROOT / "assets" / "locales"


def extract_en(text: str) -> dict:
    """Return the GDScript `const EN := { ... }` dictionary as a Python dict."""
    start = text.index("const EN := {")
    brace = text.index("{", start)
    depth = 1
    i = brace + 1
    while i < len(text) and depth > 0:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
        i += 1
    body = text[brace + 1:i - 1]
    # Drop GDScript full-line comments before evaluating.
    lines = [ln for ln in body.splitlines() if not ln.strip().startswith("#")]
    body = textwrap.dedent("\n".join(lines))
    return ast.literal_eval("{" + body + "}")


def read_po_translations(path: Path) -> dict:
    """Return {msgid: msgstr} from an existing .po file (empty dict if absent)."""
    if not path.exists():
        return {}
    out: dict = {}
    current_msgid = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("msgid "):
            current_msgid = _unescape(line[len("msgid "):].strip())
        elif line.startswith("msgstr ") and current_msgid is not None:
            out[current_msgid] = _unescape(line[len("msgstr "):].strip())
            current_msgid = None
    return out


def _unescape(text: str) -> str:
    # Minimal .po unescaping for the escapes we emit, then strip the surrounding quotes.
    text = text.replace("\\n", "\n").replace('\\"', '"').replace("\\\\", "\\")
    if len(text) >= 2 and text.startswith('"') and text.endswith('"'):
        text = text[1:-1]
    return text


def po_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_po(path: Path, en: dict, translations: dict, language: str) -> None:
    lines = [
        "# Bulwark translation file.",
        "#",
        "# Generated by tools/gen_locales.py from src/core/l10n.gd. The msgid is the English",
        "# source string; the msgstr is the localised value. Edit this file with an i18n tool to",
        "# contribute a translation. Re-run the generator after changing source strings — it",
        "# preserves the msgstr values already present here.",
        'msgid ""',
        'msgstr ""',
        f'"Language: {language}\\n"',
        '"Project-Id-Version: bulwark\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        "",
    ]
    for key in en:
        msgid = en[key]
        msgstr = translations.get(msgid, msgid if language == "en" else "")
        lines.append(f'msgid "{po_escape(msgid)}"')
        lines.append(f'msgstr "{po_escape(msgstr)}"')
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    text = L10N.read_text(encoding="utf-8")
    en = extract_en(text)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    en_existing = read_po_translations(OUT_DIR / "en.po")
    ru_existing = read_po_translations(OUT_DIR / "ru.po")

    # Source language: msgid == msgstr (identity), so the loader treats it uniformly.
    write_po(OUT_DIR / "en.po", en, en_existing, "en")
    write_po(OUT_DIR / "ru.po", en, ru_existing, "ru")

    translated = sum(1 for v in ru_existing.values() if v)
    print(f"gen_locales: wrote en.po ({len(en)} strings) and ru.po ({translated} translated)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
